#!/bin/sh
# Runs every automated check that must pass before a release, in order, and stops at the first failure.
# Run from the repository root on a clean working tree: tool/release_check.sh
# Needs Flutter 3.44+, Xcode 26, CocoaPods and a booted iOS simulator (for tool/test_native.sh).
# Manual checks that this script does not cover are listed in CONTRIBUTING.md.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
[ -f pubspec.yaml ] && [ -d pigeons ] || { echo "Run from the reception_flutter repository root." >&2; exit 1; }

summary=""
current=""
finish() {
  status=$?
  if [ "$status" -ne 0 ] && [ -n "$current" ]; then
    summary="$summary
  FAIL  $current"
  fi
  echo
  echo "== Summary"
  if [ -n "$summary" ]; then printf '%s\n' "$summary" | sed '1{/^$/d;}'; fi
  if [ "$status" -eq 0 ]; then echo "All checks passed."; else echo "Release check failed." >&2; fi
}
trap finish EXIT

step() {
  current="$1"
  echo
  echo "== $1"
}
pass() {
  summary="$summary
  ok    $current"
  current=""
}

step "clean working tree"
dirty=$(git status --porcelain)
if [ -n "$dirty" ]; then
  echo "The working tree has uncommitted changes; commit or stash them first:" >&2
  echo "$dirty" >&2
  exit 1
fi
pass

step "flutter pub get"
flutter pub get
pass

step "flutter analyze"
flutter analyze
pass

step "example: flutter pub get && flutter analyze"
(cd example && flutter pub get && flutter analyze)
pass

step "dart format --set-exit-if-changed ."
dart format --set-exit-if-changed .
pass

step "flutter test"
flutter test
pass

step "dart run tool/sync_ios_sdk.dart --check"
dart run tool/sync_ios_sdk.dart --check
pass

step "generated Pigeon code is current"
# Regenerate into build/ (git-ignored, inside the package so dart format uses the package's language version).
regen="$root/build/release_check/pigeon"
rm -rf "$regen"
mkdir -p "$regen"
sed -e "s|dartOut: 'lib/src/messages.g.dart'|dartOut: '$regen/messages.g.dart'|" \
  -e "s|'ios/reception_flutter/Sources/reception_flutter/Messages.g.swift'|'$regen/Messages.g.swift'|" \
  pigeons/reception.dart >"$regen/reception.dart"
grep -q "$regen/messages.g.dart" "$regen/reception.dart" && grep -q "$regen/Messages.g.swift" "$regen/reception.dart" || {
  echo "Could not redirect the output paths in pigeons/reception.dart; update this script." >&2
  exit 1
}
dart run pigeon --input "$regen/reception.dart"
dart format "$regen/messages.g.dart" >/dev/null
# The header names the Pigeon version, which follows pubspec.lock (not committed); only the code must match.
header='^// Autogenerated from Pigeon'
diff -u -I "$header" lib/src/messages.g.dart "$regen/messages.g.dart"
diff -u -I "$header" ios/reception_flutter/Sources/reception_flutter/Messages.g.swift "$regen/Messages.g.swift"
if [ "$(head -1 lib/src/messages.g.dart)" != "$(head -1 "$regen/messages.g.dart")" ]; then
  echo "Note: code matches, but the committed files were generated by a different Pigeon version:"
  echo "  committed: $(head -1 lib/src/messages.g.dart)"
  echo "  current:   $(head -1 "$regen/messages.g.dart")"
fi
rm -rf "$regen"
pass

step "tool/test_native.sh"
if ! xcrun simctl list devices booted | grep -q '(Booted)'; then
  echo "No booted iOS simulator. Boot one (e.g. 'xcrun simctl boot \"iPhone 17\"') and rerun." >&2
  exit 1
fi
tool/test_native.sh
pass

step "tool/pod_lint.sh"
tool/pod_lint.sh
pass

step "example: flutter build ios --simulator --debug"
(cd example && flutter build ios --simulator --debug)
pass

step "flutter pub publish --dry-run"
publish_log="$root/build/release_check/publish.log"
mkdir -p "$(dirname "$publish_log")"
flutter pub publish --dry-run >"$publish_log" 2>&1 || true
cat "$publish_log"
grep -q "Package has 0 warnings" "$publish_log" || { echo "pub publish --dry-run reported warnings or errors." >&2; exit 1; }
pass
